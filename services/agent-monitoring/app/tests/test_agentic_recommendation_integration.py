
import sys
from pathlib import Path

SERVICE_ROOT = Path(__file__).resolve().parents[2]

if str(SERVICE_ROOT) not in sys.path:
    sys.path.insert(0, str(SERVICE_ROOT))

from app.execution_monitor import graph


def test_execute_task_generates_recommendation(monkeypatch):
    # Mock the native event publisher so the test does not
    # require the Agent Monitoring API on port 8001.
    monkeypatch.setattr(
        graph,
        "publish_event",
        lambda event: {"status": "success"},
    )

    # Mock central ingestion so the test does not require
    # the central API on port 8000.
    monkeypatch.setattr(
        graph,
        "publish_central_event",
        lambda payload: {
            "status_code": 200,
            "response": "{}",
        },
    )

    state = {
        "task": "Check transaction status",
        "messages": [],
        "trajectory": [],
        "tool_calls": [],
        "tool_results": [
            {
                "tool": "check_transaction_status",
                "output": None,
                "status": "failed",
                "latency_ms": 5.0,
                "error": "Transaction service failed.",
                "trace_id": "trace-test",
                "span_id": "span-test",
                "tool_call_id": "call-test",
            }
        ],
        "telemetry_events": [
            {
                "name": "tool_node",
                "status": "failed",
                "latency_ms": 5.0,
                "error": "Transaction service failed.",
            }
        ],
        "memory": [],
        "trace_id": "trace-test",
        "attempt_count": 0,
        "max_attempts": 3,
        "execution_start_time": None,
    }

    result = graph.execute_task(state)

    assert result["failure_analysis"]["failure_detected"] is True
    assert result["diagnosis"]["diagnosis_detected"] is True

    recommendation = result["recommendation"]

    assert recommendation["recommendation_detected"] is True
    assert recommendation["priority"] == "high"
    assert recommendation["action"] == "retry_or_validate_tool"

    event = result["event"]

    assert "recommendation" in event["metadata"]
    assert (
        event["metadata"]["recommendation"]["action"]
        == "retry_or_validate_tool"
    )

    # Verify Agentic analytics are generated by the real
    # execution finalization path.
    analytics = result["analytics"]

    assert analytics["execution_success"] is False
    assert analytics["trajectory_length"] == 1
    assert analytics["tool_result_count"] == 1
    assert analytics["tool_failure_count"] == 1
    assert analytics["execution_failure_count"] == 2
    assert analytics["telemetry_event_count"] == 2

    # The execute_task telemetry latency is measured dynamically
    # with perf_counter(), so the total will be slightly above
    # the supplied 5 ms tool latency.
    assert analytics["total_telemetry_latency_ms"] >= 5.0

    # Verify the same analytics are included in the published event.
    event_analytics = event["metadata"]["analytics"]

    assert event_analytics == analytics
