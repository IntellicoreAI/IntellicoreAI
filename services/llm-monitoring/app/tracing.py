"""Trace-context propagation for LLM requests.

When an LLM request is made *inside* an Agentic AI execution, the LLM event must
carry the agent's ``trace_id`` so the Decision Pipeline can correlate the two.

Precedence (first match wins):
  1. ``trace_id`` / ``span_id`` / ``parent_span_id`` in the JSON body
  2. ``X-Trace-Id`` / ``X-Parent-Span-Id`` HTTP headers
  3. W3C ``traceparent`` header (``00-<32 hex trace>-<16 hex parent span>-<flags>``)
  4. nothing supplied -> a new trace is generated by the caller (standalone LLM call)

The agent's own trace ids are UUID strings, so UUIDs and W3C hex ids are both accepted.
"""
import re
from typing import Mapping

_TRACE_ID_RE = re.compile(r"^[A-Za-z0-9._:-]{1,255}$")
_TRACEPARENT_RE = re.compile(r"^[0-9a-f]{2}-([0-9a-f]{32})-([0-9a-f]{16})-[0-9a-f]{2}$")

TRACE_HEADER = "X-Trace-Id"
PARENT_SPAN_HEADER = "X-Parent-Span-Id"


def _clean(value: str | None) -> str | None:
    if value is None:
        return None
    value = str(value).strip()
    return value if value and _TRACE_ID_RE.match(value) else None


def resolve_trace_context(
    body_trace_id: str | None = None,
    body_parent_span_id: str | None = None,
    headers: Mapping[str, str] | None = None,
) -> dict:
    """Return ``{trace_id, parent_span_id, trace_source}``.

    ``trace_id`` is ``None`` when nothing was propagated; the caller then generates one
    and the event is recorded with ``trace_source='generated'``.
    """
    h = {k.lower(): v for k, v in (headers or {}).items()}

    body_trace = _clean(body_trace_id)
    if body_trace:
        return {"trace_id": body_trace,
                "parent_span_id": _clean(body_parent_span_id) or _clean(h.get(PARENT_SPAN_HEADER.lower())),
                "trace_source": "request_body"}

    header_trace = _clean(h.get(TRACE_HEADER.lower()))
    if header_trace:
        return {"trace_id": header_trace,
                "parent_span_id": _clean(body_parent_span_id) or _clean(h.get(PARENT_SPAN_HEADER.lower())),
                "trace_source": "header"}

    match = _TRACEPARENT_RE.match((h.get("traceparent") or "").strip().lower())
    if match and match.group(1) != "0" * 32:
        return {"trace_id": match.group(1),
                "parent_span_id": _clean(body_parent_span_id) or match.group(2),
                "trace_source": "traceparent"}

    return {"trace_id": None, "parent_span_id": _clean(body_parent_span_id), "trace_source": "generated"}


def propagation_headers(trace_id: str, span_id: str | None = None) -> dict[str, str]:
    """Headers an agent should attach when it calls the LLM monitoring service."""
    headers = {TRACE_HEADER: trace_id}
    if span_id:
        headers[PARENT_SPAN_HEADER] = span_id
    return headers
