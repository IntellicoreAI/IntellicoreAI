
"""
Prediction Drift Monitoring
----------------------------

Compares the model's current prediction behavior against
a fixed reference prediction distribution.

Reference predictions are generated by the trained XGBoost
model on the processed test dataset.

Current predictions are read from ML telemetry events.

Outputs:
    data/artifacts/monitoring/prediction_baseline.json
    data/artifacts/monitoring/prediction_drift_report.json
"""

import os
from pathlib import Path
import json

import numpy as np
import pandas as pd
from scipy.stats import ks_2samp
from xgboost import XGBClassifier


# ============================================================
# PROJECT PATHS
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[4]

TEST_PATH = (
    PROJECT_ROOT
    / "data"
    / "processed"
    / "test.csv"
)

MODEL_PATH = (
    PROJECT_ROOT
    / "data"
    / "artifacts"
    / "xgboost"
    / "model.json"
)

FEATURE_NAMES_PATH = (
    PROJECT_ROOT
    / "data"
    / "artifacts"
    / "xgboost"
    / "feature_names.json"
)

TELEMETRY_PATH = Path(
    os.getenv(
        "INTELLICORE_TELEMETRY_PATH",
        str(PROJECT_ROOT / "data" / "telemetry" / "prediction_events.jsonl"),
    )
)
if not TELEMETRY_PATH.is_absolute():
    TELEMETRY_PATH = PROJECT_ROOT / TELEMETRY_PATH

OUTPUT_DIR = (
    PROJECT_ROOT
    / "data"
    / "artifacts"
    / "monitoring"
)

PREDICTION_BASELINE_PATH = (
    OUTPUT_DIR
    / "prediction_baseline.json"
)

PREDICTION_DRIFT_REPORT_PATH = (
    OUTPUT_DIR
    / "prediction_drift_report.json"
)

CONFIG_PATH = (
    OUTPUT_DIR
    / "monitoring_config.json"
)

PREDICTION_THRESHOLD = 0.50


# ============================================================
# CONFIGURATION
# ============================================================

def load_prediction_drift_config() -> dict:
    """Load and validate prediction-drift configuration."""

    with open(CONFIG_PATH, "r", encoding="utf-8-sig") as file:
        config = json.load(file)

    prediction_config = config.get("prediction_drift", {})

    if not isinstance(prediction_config, dict):
        raise ValueError(
            "prediction_drift configuration must be a JSON object."
        )

    method = prediction_config.get("method", "ks_2samp")

    if method != "ks_2samp":
        raise ValueError(
            "prediction_drift.method must be 'ks_2samp'."
        )

    alpha = prediction_config.get("significance_level")

    if (
        isinstance(alpha, bool)
        or not isinstance(alpha, (int, float))
        or not 0 < alpha < 1
    ):
        raise ValueError(
            "prediction_drift.significance_level must be "
            "a number strictly between 0 and 1."
        )

    return {
        "method": method,
        "significance_level": float(alpha),
    }


# ============================================================
# UTILITY FUNCTIONS
# ============================================================

def calculate_statistics(values):
    """Calculate descriptive statistics for prediction probabilities."""

    values = np.asarray(values, dtype=float)

    if values.size == 0:
        raise ValueError(
            "Cannot calculate statistics for an empty array."
        )

    if not np.isfinite(values).all():
        raise ValueError(
            "Statistics input contains non-finite values."
        )

    return {
        "count": int(len(values)),
        "mean": float(np.mean(values)),
        "median": float(np.median(values)),
        "std": float(np.std(values)),
        "min": float(np.min(values)),
        "max": float(np.max(values)),
        "q01": float(np.quantile(values, 0.01)),
        "q05": float(np.quantile(values, 0.05)),
        "q25": float(np.quantile(values, 0.25)),
        "q50": float(np.quantile(values, 0.50)),
        "q75": float(np.quantile(values, 0.75)),
        "q95": float(np.quantile(values, 0.95)),
        "q99": float(np.quantile(values, 0.99)),
    }


def load_json(path):
    """Load a JSON file."""

    with open(path, "r", encoding="utf-8-sig") as file:
        return json.load(file)


def validate_probabilities(values, name):
    """Validate and return an array of probability values."""

    values = np.asarray(values, dtype=float)

    if values.ndim != 1:
        raise ValueError(
            f"{name} probabilities must be a one-dimensional array."
        )

    if values.size == 0:
        raise ValueError(
            f"{name} probabilities must not be empty."
        )

    if not np.isfinite(values).all():
        raise ValueError(
            f"{name} probabilities contain non-finite values."
        )

    if ((values < 0) | (values > 1)).any():
        raise ValueError(
            f"{name} probabilities must be between 0 and 1."
        )

    return values


# ============================================================
# LOAD FEATURE NAMES
# ============================================================

def load_feature_names():
    """Load feature names used by the trained XGBoost model."""

    feature_names = load_json(FEATURE_NAMES_PATH)

    if not isinstance(feature_names, list) or not feature_names:
        raise ValueError(
            "feature_names.json must contain a non-empty list."
        )

    if not all(isinstance(name, str) for name in feature_names):
        raise ValueError(
            "All feature names must be strings."
        )

    return feature_names


# ============================================================
# GENERATE REFERENCE PREDICTIONS
# ============================================================

def generate_reference_predictions():
    """
    Generate model predictions on the fixed test dataset.

    These predictions become the reference distribution
    for prediction-drift monitoring.
    """

    print("\n" + "=" * 70)
    print("GENERATING REFERENCE PREDICTIONS")
    print("=" * 70)

    if not TEST_PATH.exists():
        raise FileNotFoundError(
            f"Reference test dataset not found: {TEST_PATH}"
        )

    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Trained model not found: {MODEL_PATH}"
        )

    if not FEATURE_NAMES_PATH.exists():
        raise FileNotFoundError(
            f"Feature names file not found: {FEATURE_NAMES_PATH}"
        )

    test_df = pd.read_csv(TEST_PATH)
    feature_names = load_feature_names()

    # Separate features from target.
    if "SeriousDlqin2yrs" in test_df.columns:
        X_reference = test_df.drop(
            columns=["SeriousDlqin2yrs"]
        )
    else:
        X_reference = test_df.copy()

    # Ensure required features exist.
    missing_features = [
        feature
        for feature in feature_names
        if feature not in X_reference.columns
    ]

    if missing_features:
        raise ValueError(
            f"Missing required features: {missing_features}"
        )

    # Preserve the model's expected feature order.
    X_reference = X_reference[feature_names]

    if X_reference.empty:
        raise ValueError(
            "Reference test dataset contains no rows."
        )

    # Load trained model.
    model = XGBClassifier()
    model.load_model(str(MODEL_PATH))

    # Generate positive-class probabilities.
    probabilities = model.predict_proba(X_reference)[:, 1]
    probabilities = validate_probabilities(
        probabilities,
        "Reference",
    )

    predictions = (
        probabilities >= PREDICTION_THRESHOLD
    ).astype(int)

    probability_statistics = calculate_statistics(probabilities)

    class_distribution = {
        "class_0": int(np.sum(predictions == 0)),
        "class_1": int(np.sum(predictions == 1)),
    }

    positive_prediction_rate = float(
        np.mean(predictions == 1)
    )

    baseline = {
        "description": (
            "Reference prediction distribution generated by "
            "the trained XGBoost credit-risk model on the "
            "processed test dataset."
        ),
        "model": {
            "model_name": "xgboost_credit_risk",
            "model_version": "1.0",
        },
        "dataset": {
            "path": str(TEST_PATH.relative_to(PROJECT_ROOT)),
            "rows": int(len(X_reference)),
        },
        "prediction_threshold": PREDICTION_THRESHOLD,
        "prediction_probability_statistics": probability_statistics,
        "predicted_class_distribution": class_distribution,
        "positive_prediction_rate": positive_prediction_rate,
    }

    # Save baseline.
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    with open(
        PREDICTION_BASELINE_PATH,
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(baseline, file, indent=4)

    print(f"Reference rows: {len(X_reference):,}")
    print(
        f"Mean probability: "
        f"{probability_statistics['mean']:.6f}"
    )
    print(
        f"Median probability: "
        f"{probability_statistics['median']:.6f}"
    )
    print(
        f"Positive prediction rate: "
        f"{positive_prediction_rate:.4%}"
    )
    print(
        f"\nSaved prediction baseline to:\n"
        f"{PREDICTION_BASELINE_PATH}"
    )

    return probabilities


# ============================================================
# LOAD CURRENT TELEMETRY
# ============================================================

def load_current_predictions():
    """Read prediction probabilities and classes from telemetry JSONL."""

    print("\n" + "=" * 70)
    print("LOADING CURRENT TELEMETRY")
    print("=" * 70)

    if not TELEMETRY_PATH.exists():
        raise FileNotFoundError(
            f"Prediction telemetry not found: {TELEMETRY_PATH}"
        )

    probabilities = []
    predicted_classes = []
    malformed_events = 0

    with open(
        TELEMETRY_PATH,
        "r",
        encoding="utf-8-sig",
    ) as file:
        for line_number, line in enumerate(file, start=1):
            line = line.strip()

            if not line:
                continue

            try:
                event = json.loads(line)

                if not isinstance(event, dict):
                    raise ValueError("Event must be a JSON object.")

                prediction = event.get("prediction", {})

                if not isinstance(prediction, dict):
                    raise ValueError(
                        "Prediction field must be a JSON object."
                    )

                probability = prediction.get(
                    "prediction_probability"
                )
                predicted_class = prediction.get("predicted_class")

                # Keep each probability paired with its class.
                if probability is None or predicted_class is None:
                    raise ValueError(
                        "Prediction probability or predicted class is missing."
                    )

                probability = float(probability)
                predicted_class = int(predicted_class)

                if not np.isfinite(probability) or not 0 <= probability <= 1:
                    raise ValueError(
                        "Prediction probability must be finite and in [0, 1]."
                    )

                if predicted_class not in (0, 1):
                    raise ValueError(
                        "Predicted class must be 0 or 1."
                    )

                probabilities.append(probability)
                predicted_classes.append(predicted_class)

            except (json.JSONDecodeError, TypeError, ValueError) as exc:
                malformed_events += 1
                raise ValueError(
                    f"Invalid prediction telemetry at line "
                    f"{line_number}: {exc}"
                ) from exc

    if not probabilities:
        raise ValueError(
            "No valid prediction probabilities found in telemetry."
        )

    print(f"Current prediction events: {len(probabilities):,}")
    print(f"Malformed events: {malformed_events}")

    return (
        np.asarray(probabilities, dtype=float),
        np.asarray(predicted_classes, dtype=int),
    )


# ============================================================
# DETECT PREDICTION DRIFT
# ============================================================

def detect_prediction_drift(
    reference_probabilities,
    current_probabilities,
    current_classes,
):
    """Compare reference and current prediction distributions."""

    print("\n" + "=" * 70)
    print("PREDICTION DRIFT DETECTION")
    print("=" * 70)

    # Load configured test method and significance threshold.
    drift_config = load_prediction_drift_config()
    alpha = drift_config["significance_level"]

    reference_probabilities = validate_probabilities(
        reference_probabilities,
        "Reference",
    )

    current_probabilities = validate_probabilities(
        current_probabilities,
        "Current",
    )

    current_classes = np.asarray(current_classes)

    if current_classes.ndim != 1:
        raise ValueError(
            "Current predicted classes must be a one-dimensional array."
        )

    if len(current_classes) != len(current_probabilities):
        raise ValueError(
            "Current predicted classes and probabilities "
            "must have the same length."
        )

    if not np.isin(current_classes, [0, 1]).all():
        raise ValueError(
            "Current predicted classes must contain only 0 or 1."
        )

    # KS two-sample test.
    ks_statistic, p_value = ks_2samp(
        reference_probabilities,
        current_probabilities,
    )

    drift_detected = bool(p_value < alpha)

    # Probability statistics.
    reference_statistics = calculate_statistics(
        reference_probabilities
    )

    current_statistics = calculate_statistics(
        current_probabilities
    )

    # Class distribution uses the same probability threshold
    # for reference and current predictions.
    reference_classes = (
        reference_probabilities >= PREDICTION_THRESHOLD
    ).astype(int)

    current_classes_from_probabilities = (
        current_probabilities >= PREDICTION_THRESHOLD
    ).astype(int)

    reference_class_distribution = {
        "class_0": int(np.sum(reference_classes == 0)),
        "class_1": int(np.sum(reference_classes == 1)),
    }

    current_class_distribution = {
        "class_0": int(
            np.sum(current_classes_from_probabilities == 0)
        ),
        "class_1": int(
            np.sum(current_classes_from_probabilities == 1)
        ),
    }

    reference_positive_rate = float(
        np.mean(reference_classes == 1)
    )

    current_positive_rate = float(
        np.mean(current_classes_from_probabilities == 1)
    )

    positive_rate_difference = (
        current_positive_rate - reference_positive_rate
    )

    # Build report.
    report = {
        "monitoring_type": "prediction_drift",
        "method": {
            "distribution_test": (
                "Kolmogorov-Smirnov two-sample test"
            ),
            "configuration_method": drift_config["method"],
            "alpha": alpha,
            "configured_significance_level": alpha,
            "null_hypothesis": (
                "Reference and current prediction probability "
                "distributions are drawn from the same distribution."
            ),
        },
        "model": {
            "model_name": "xgboost_credit_risk",
            "model_version": "1.0",
        },
        "reference": {
            "dataset": str(
                TEST_PATH.relative_to(PROJECT_ROOT)
            ),
            "sample_count": int(len(reference_probabilities)),
            "statistics": reference_statistics,
            "predicted_class_distribution": (
                reference_class_distribution
            ),
            "positive_prediction_rate": reference_positive_rate,
        },
        "current": {
            "telemetry": str(
                TELEMETRY_PATH.relative_to(PROJECT_ROOT)
            ),
            "sample_count": int(len(current_probabilities)),
            "statistics": current_statistics,
            "predicted_class_distribution": (
                current_class_distribution
            ),
            "positive_prediction_rate": current_positive_rate,
        },
        "comparison": {
            "ks_statistic": float(ks_statistic),
            "p_value": float(p_value),
            "positive_prediction_rate_difference": (
                float(positive_rate_difference)
            ),
            "drift_detected": drift_detected,
        },
        "overall_status": (
            "drift_detected"
            if drift_detected
            else "no_significant_drift"
        ),
    }

    # Print result.
    print(
        f"Reference mean probability: "
        f"{reference_statistics['mean']:.6f}"
    )
    print(
        f"Current mean probability:   "
        f"{current_statistics['mean']:.6f}"
    )
    print(
        f"Reference positive rate: "
        f"{reference_positive_rate:.4%}"
    )
    print(
        f"Current positive rate:   "
        f"{current_positive_rate:.4%}"
    )
    print(f"\nKS statistic: {ks_statistic:.6f}")
    print(f"p-value:      {p_value:.6f}")
    print(f"Significance level: {alpha:.4f}")

    if drift_detected:
        print("\nSTATUS: PREDICTION DRIFT DETECTED")
    else:
        print("\nSTATUS: NO SIGNIFICANT PREDICTION DRIFT")

    # Save report.
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    with open(
        PREDICTION_DRIFT_REPORT_PATH,
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(report, file, indent=4)

    print(
        f"\nSaved prediction drift report to:\n"
        f"{PREDICTION_DRIFT_REPORT_PATH}"
    )

    return report


# ============================================================
# MAIN
# ============================================================

def main():
    """Run prediction-drift monitoring."""

    print("\n" + "=" * 70)
    print("INTELLICORE AI - PREDICTION DRIFT MONITORING")
    print("=" * 70)

    # Validate configuration before doing expensive model work.
    load_prediction_drift_config()

    # Generate fixed reference predictions.
    reference_probabilities = generate_reference_predictions()

    # Load current telemetry predictions.
    current_probabilities, current_classes = load_current_predictions()

    # Compare distributions.
    detect_prediction_drift(
        reference_probabilities,
        current_probabilities,
        current_classes,
    )

    print("\n" + "=" * 70)
    print("PREDICTION DRIFT MONITORING COMPLETE")
    print("=" * 70)


if __name__ == "__main__":
    main()
